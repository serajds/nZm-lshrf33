import { createHash } from "node:crypto";
import type { ReportActivityAnalysis } from "./report-activity-analysis";

export function validApprovedProgress(value: unknown): value is number {
  return typeof value === "number" && Number.isFinite(value) && value >= 0 && value <= 100;
}

export function approvedReportFingerprint(reportDate: string, periodStart: string, periodEnd: string, progress: number, analysis?: ReportActivityAnalysis): string {
  const inputs: unknown[] = [reportDate, periodStart, periodEnd, progress];
  if (analysis) inputs.push(analysis);
  return (analysis ? "approved-activities:" : "approved:") + createHash("sha256")
    .update(JSON.stringify(inputs)).digest("hex");
}

